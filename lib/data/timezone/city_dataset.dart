class CityRecord {
  const CityRecord({
    required this.city,
    required this.region,
    required this.country,
    required this.ianaTimezone,
  });

  final String city;
  final String region;
  final String country;
  final String ianaTimezone;

  String get label => '$city, $region, $country';

  bool matches(String query) {
    final normalized = query.trim().toLowerCase();
    if (normalized.isEmpty) return true;
    return city.toLowerCase().contains(normalized) ||
        region.toLowerCase().contains(normalized) ||
        country.toLowerCase().contains(normalized) ||
        ianaTimezone.toLowerCase().contains(normalized) ||
        label.toLowerCase().contains(normalized);
  }
}

